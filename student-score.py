scores = [75, 82, 91, 68, 88]

#Print all scores.
print("Scores: ", scores)

#Sort them.
scores.sort()
print("Sorted: ", scores)

#Print the highest score.
print("Highest score: ", max(scores))

#Print the lowest score.
print("Lowest score: ", min(scores))

#Calculate the average.
average = sum(scores)/len(scores)
print("Average: ", average)